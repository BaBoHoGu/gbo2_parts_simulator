// 사전 표기 통일 — 뜻은 같은데 적는 법이 갈린 자리를 한쪽으로 모은다.
//   node tools/normalize_i18n.js
// 숫자가 바뀌면 그 칸은 건드리지 않고 경고한다(안전 장치).
const fs = require('fs');
const path = require('path');
const UNITS = [['秒','초'],['倍','배'],['発','발'],['回','회'],['射','사'],['分','분'],
  ['等','등'],['最大','최대'],['ヒット','히트'],['腕','팔'],['門','문'],['丁','정'],['基','기'],['合計','합계'],['約','약'],['共鳴','공명']];
const RULES = [
  [/오버히트/g, '오버 히트'],           // 공식은 띄어 쓴다
  [/제어기구/g, '제어 기구'],
  [/실드장 특수 완충재/g, '실드 병장 특수 완충재'],   // MT 가 「병」을 흘린 자리
  [/메커니즘/g, '기구'],
  [/병장/g, '무장'],          // 공식은 兵装·武装 모두 「무장」
  // 위키가 ブースト射撃可 와 高速移動射撃可 를 섞어 쓴다. 같은 동작이고
  // 공식은 「고속 이동」만 쓴다(「부스트」는 공지에 한 번도 안 나온다).
  // 「슈팅 부스트」·「오버 부스트」·「플랩 부스터」는 스킬 이름이라 건드리지 않는다.
  [/부스트 사격/g, '고속 이동 사격'],
  [/부스트 이동/g, '고속 이동'],
  [/리로드/g, '재장전'],
  [/큰 경직/g, '강경직'],
  // MT 가 よろけ値 를 불릿마다 제각각 흘린다 — 「요로케값」(음차 그대로) ·
  // 「사격비」(値 를 比 로 읽음) · 「알맞은 값」(適した値 로 오독). 칸 단위 대조
  // 검사는 같은 칸의 다른 불릿에 「경직」이 있으면 통과시켜서 이걸 못 봤다.
  [/요로케\s?값/g, '경직치'],
  [/요로케치/g, '경직치'],
  [/사격비를/g, '사격 경직치를'],
  [/공격의 알맞은 값을/g, '공격의 경직치를'],
  [/사격속성의 알맞은 값을/g, '사격 속성의 경직치를'],
  [/빔속성/g, '빔 속성'],          // MT 가 붙여 쓴 자리 — 다른 칸은 모두 띄어 쓴다
  [/사격받는 대미지/g, '사격 받는 대미지'],
  [/사격경직치/g, '사격 경직치'],
  // 音차가 그대로 남은 자리. 大よろけ 가 앞에 오므로 「대요로케」를 먼저 본다.
  [/대요로케/g, '강경직'],
  [/요로케/g, '경직'],
  [/주 대미지\s?\+/g, '가한 대미지 +'],   // 与ダメージ 를 「주(主)」로 읽은 자리
  [/시대 미지/g, '시 대미지'],            // 「時ダメージ」를 「시대 + 미지」로 끊은 자리
  [/경직치을/g, '경직치를'],
  [/경직치를\?%/g, '경직치를 ?%'],
  // 「よろけ値を N%かつ小数点以下切り捨て で計算する」의 꼬리가 60종으로 흩어져 있었다
  // (111칸). 이음말이 「또한」·「그리고」·쉼표로 갈리고 동사가 「잘라내어」·
  // 「잘라내기로」·「버림으로」로 갈렸다. 뜻은 하나뿐이라 꼬리만 한 표기로 모은다.
  // 앞머리(받은 공격의 / 고속 이동 중에 …)는 원문이 실제로 달라서 그대로 둔다.
  // 「…계산한다」와 「…계산」은 문장이냐 불릿이냐의 차이라 어미는 살린다.
  [/\s*(?:로)?\s*,?\s*(?:또한|그리고)?\s*소수점 이하\s*(?:잘라내어|잘라내기로|버림으로)\s*계산/g,
    ', 소수점 이하 버림으로 계산'],
  [/소수점 이하 잘라내기(?!로)/g, '소수점 이하 버림'],
  [/통상 ?시공 ?중 사용 불가/g, '통상 시 공중 사용 불가'],   // 通常時空中使用不可
  // マニューバーアーマー 를 MT 가 「매뉴 바 + 아머」로 끊었고, 같은 이름이
  // 어떤 칸에선 「마뉴」로 시작한다. 스킬 이름이라 한 표기여야 한다.
  [/(?:매뉴|마뉴) ?바 ?아머/g, '매뉴버 아머'],
  // 「발동 중」(384칸) 처럼 띄어 쓴 쪽이 기준인데 붙여 쓴 칸이 130개쯤 섞여 있다.
  // 낱말을 늘어놓는다 — 「공중」·「명중」처럼 중이 낱말의 일부인 자리를 건드리면 안 된다.
  [/(발동|사용|이동|고속 ?이동|공격|장비|낙하|집속|다운|전도|기동|전개|선택|개시|변형|가드|재장전|카운터|가동|동작|장착|회피)중(?=[에,\s의]|$)/g,
    '$1 중'],
];
// 존댓말체 어미 → 평서체. 다른 항목이 전부 평서체라 섞이면 눈에 띈다.
// MT 가 고르는 문체라 재번역해도 안 고쳐진다 — 나온 어미만 열거해 바꾼다.
const POLITE = [
  [/가능합니다/g, '가능하다'], [/무효화합니다/g, '무효화한다'], [/있습니다/g, '있다'],
  [/없습니다/g, '없다'], [/않습니다/g, '않는다'], [/확장됩니다/g, '확장된다'],
  [/발생합니다/g, '발생한다'], [/비활성화합니다/g, '비활성화한다'], [/줄입니다/g, '줄인다'],
  [/소비합니다/g, '소비한다'], [/수행됩니다/g, '수행된다'], [/완화됩니다/g, '완화된다'],
  [/표시됩니다/g, '표시된다'], [/얻습니다/g, '얻는다'], [/상승합니다/g, '상승한다'],
  [/증가합니다/g, '증가한다'], [/회복됩니다/g, '회복된다'], [/변화합니다/g, '변화한다'],
  [/줄어 듭니다/g, '줄어든다'], [/됩니다/g, '된다'], [/합니다/g, '한다'],
];
// 「」'' "" 【】 안(스킬명·고유명사)은 건드리지 않는다.
const PROT = /(「[^」]*」|'[^']*'|"[^"]*"|【[^】]*】)/g;

// 다만 이름 자체가 깨진 자리는 따옴표 안에서도 고쳐야 한다. MT 가 이름을
// 낱말로 끊어 놓으면 문장 안 인용(「…」)과 목록의 표기가 서로 갈린다.
// 이름이니 여기 적힌 것만 손댄다 — 일반 규칙을 따옴표 안으로 들이지 않는다.
const NAMES = [
  [/(?:매뉴|마뉴) ?바 ?아머/g, '매뉴버 아머'],   // マニューバーアーマー
];
const all = RULES.concat(POLITE);
const apply = s => s.split(PROT).map((seg, i) => i % 2
  ? NAMES.reduce((a, [re, to]) => a.replace(re, to), seg)
  : all.reduce((a, [re, to]) => a.replace(re, to), UNITS.reduce((a, [ja, ko]) => a.split(ja).join(ko), seg))).join('');
const num = s => (String(s).match(/\d+(?:\.\d+)?/g) || []).join(',');

let total = 0, skipped = 0;
for (const f of ['skill_text', 'weapon_note', 'weapons', 'parts']) {
  const p = path.join(__dirname, '..', 'data', 'i18n', f + '.json');
  let o; try { o = JSON.parse(fs.readFileSync(p, 'utf8')); } catch { continue; }
  let n = 0;
  const one = (k, cur, set) => {
    const t = apply(cur);
    if (t === cur) return 0;
    if (num(t) !== num(cur)) { skipped++; console.log('  숫자가 바뀌어 건너뜀: ' + k.slice(0, 40)); return 0; }
    set(t); return 1;
  };
  for (const [k, v] of Object.entries(o)) {
    if (typeof v === 'string') n += one(k, v, t => { o[k] = t; });
    else if (v && typeof v === 'object')
      for (const fld of ['n', 'd'])
        if (typeof v[fld] === 'string') n += one(k, v[fld], t => { v[fld] = t; });
  }
  if (n) fs.writeFileSync(p, JSON.stringify(o, null, 1) + '\n', 'utf8');
  console.log(`  ${f.padEnd(12)} ${n}칸`);
  total += n;
}
console.log(`표기 통일 ${total}칸 · 숫자가 바뀌어 건너뛴 칸 ${skipped}`);
