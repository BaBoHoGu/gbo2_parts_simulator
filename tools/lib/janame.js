// 「한국어 이름 - 원문」 꼬리표 — 일본어 잔존 검사에서 봐 줄 자리를 **한 곳에** 둔다.
//
// 왜 있는가 — 한국어 이름이 겹치는 기체가 있다. カプール 과 カプル 은 둘 다 「카풀」이라
// 목록에서 구분이 안 됐다. 그래서 뒤에 「 - 원문」을 달아 가른다(사용자 지시):
//     카풀 - カプール LV4   /   카풀 - カプル LV1
// 이건 번역이 빠진 것이 아니라 **일부러 적은 것**이라, 일본어 검사가 봐 줘야 한다.
//
// 왜 한 곳에 두는가 — 이 규칙을 쓰는 검사가 셋(smoke · ja_leak_check · unmodview_check)이고,
// 둘은 브라우저 안(page.evaluate)에서 돈다. 각자 정규식을 베껴 적으면 언젠가 갈린다.
// 그래서 **문자열로** 내보내, 브라우저로 넘겨 그 안에서 다시 만들게 한다.
//
// 봐 주는 범위는 좁게 — 「 - 」 **바로 뒤의 일본어 덩어리만** 지운다:
//   · 끝(`$`)에 고정하지 않는다. 이름 뒤에 「 LV4」가 붙어 꼬리가 문장 끝이 아니다.
//   · 글자 종류로 멈춘다. 한글을 넣지 않았으므로 앞쪽 한국어까지 먹지 않는다.
//   · 그래서 「카풀ール - カプール」처럼 **꼬리 밖**에 남은 일본어는 그대로 걸린다(심어서 확인).
// 지금 이름에 「 - 」를 쓰는 기체는 이 둘뿐이다(전수 확인).
const TAIL_SRC = '\\s-\\s[ぁ-ゖァ-ヺ一-鿿ーｰ・（）()／/A-Za-z0-9．.]+';

/** 꼬리표를 지운 글자. 검사는 이 결과에 일본어가 남았는지만 본다. */
const stripDisambig = s => String(s).replace(new RegExp(TAIL_SRC, 'g'), '');

module.exports = { TAIL_SRC, stripDisambig };
