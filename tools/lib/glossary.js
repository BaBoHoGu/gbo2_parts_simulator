// MT(구글) 로 보내기 전에 게임 용어를 한글로 미리 바꿔 둔다.
//
// 왜: gtx 는 게임 용어를 일반어로 옮긴다. 「よろけ」가 「쑥쑥」·「잡음」·「여유」가 되고
// 아예 문장에서 사라지기도 한다(2026-09-12 실측 271칸). 「비틀」 같은 금지어를 찾는
// 검사로는 이런 오역이 안 걸린다 — 금지어가 안 나오기 때문이다.
//
// 어떻게: 일본어 자리에 한글을 먼저 박아 두면 gtx 가 그 한글을 그대로 통과시킨다.
// 실측에서 토큰(ZZ1ZZ·《1》)보다 문장이 자연스러웠다.
//   「…生じるよろけの発生を軽減」 → 「…생기는 경직의 발생을 경감」
//
// 긴 것부터 적용해야 한다. 「よろけ」가 「大よろけ」보다 먼저 걸리면 「강경직」이 안 나온다.
const PRE = [
  // 경직 계열 — 이 게임의 핵심 전투 개념이라 틀리면 설명이 무의미해진다
  /* 「有」까지 묶어 둔다 — 한글만 박아 두면 뒤따르는 일본어와 붙어 MT 가 뭉갠다.
     실측: 「大よろけ有」 → 보호 후 「강경직有」 → MT 가 「강경 직유」로 돌려줬다.
     낱말이 쪼개져 나오므로 금지어 검사로도, POST 치환으로도 못 잡는다 —
     붙을 자리를 아예 없애는 것이 유일하게 확실하다. */
  ['大よろけ有', '강경직 있음'], ['よろけ有', '경직 있음'],
  ['大よろけ', '강경직'], ['蓄積よろけ', '축적 경직'], ['よろけ値', '경직치'], ['よろけ', '경직'],
  /* 「有」까지 묶는 이유는 위 大よろけ有 와 같다 — 한글만 박으면 뒤따르는 일본어와 붙어
     MT 가 뭉갠다. ひるみ 는 여기에 더해 **대조 목록(CHECK)에 없어서** 음차된 칸이
     무장 13종·기체 14기에 남아 있었다(「히루미 유」). 목록에 없으면 영영 안 걸린다. */
  ['ひるみ有', '움찔 있음'], ['ひるみ無', '움찔 없음'], ['ひるみ', '움찔'], ['のけぞり', '젖혀짐'],
  // 공식 한국어판(bo2.ggame.jp/kr) 조정 공지·개발 일지에서 확인한 표기.
  // 공지는 게임 내 스킬·무장 설명을 그대로 인용하므로 게임 내 표기로 본다.
  // 다만 「よろけ」만은 「경직」을 쓴다 — 공식은 「비틀거림」이지만
  // 커뮤니티 통용 표기이고 지시서 용어집이 「비틀거림」을 ✗로 지정했다.
  ['被ダメージ', '받는 대미지'], ['与ダメージ', '가한 대미지'], ['ダメージ', '대미지'],
  ['スラスター', '슬러스터'], ['兵装', '무장'], ['シールド', '실드'],
  ['オーバーヒート', '오버 히트'], ['リロード', '재장전'], ['制御機構', '제어 기구'], ['フレキシブル', '플렉시블'],
  ['サイコミュ', '사이코뮤'],
  ['脚部', '다리'], ['頭部', '머리'], ['背部', '등'], ['左腕', '왼팔'],
  // gtx 가 「水場」을 「수장」으로 옮겨 놓았다 — 물가를 가리키는 말이라 뜻이 어긋난다
  ['水場', '물가'],
  ['ファンネル', '판넬'], ['停止撃ち', '정지 사격'], ['本スキル', '본 스킬'],
  ['自機', '자기 기체'], ['鍔迫り合い', '격투 맞부딪힘'],
];
const ORDER = PRE.slice().sort((a, b) => b[0].length - a[0].length);

// 「」'' "" 【】 안은 스킬명·고유명사라 건드리지 않는다.
const PROT = /(「[^」]*」|'[^']*'|"[^"]*"|【[^】]*】)/g;

// MT 로 보내기 전 일본어에 적용.
const protect = s =>
  String(s).split(PROT).map((seg, i) =>
    i % 2 ? seg : ORDER.reduce((a, [jp, ko]) => a.split(jp).join(ko), seg)).join('');

/* MT 로 보낸 **뒤** 에 적용 — protect() 로 한글을 박아 보내도 gtx 가 되돌려 놓는 말이 있다.
   실측: 「슬러스터」를 박아 보냈는데 「스러스터」로 바꿔 돌려줬다(2026-09-22, 7칸).
   protect() 만으로는 못 막는다 — 보낸 글자와 받은 글자가 다른 것이라, 앞단에서 할 수 있는
   일이 없다. 그래서 받은 뒤에 다시 맞춘다. **본 것만** 적는다(지어내지 않는다). */
const POST = [
  [/스러스터/g, '슬러스터'],
  /* ひるみ 가 음차로 굳은 칸이 18개 있었다(「히루미 유」). 사전은 캐시라 다시 안 만들어지고,
     MT 는 이 불릿들을 더 못 옮긴다 — 그래서 **받은 뒤 고치는** 이 자리에서 바로잡는다.
     「有」가 「유」로 음차된 것까지 함께 본다. 긴 것을 먼저 둬야 「움찔 유」로 끝나지 않는다. */
  /* 맨 「히루미」는 **일부러 안 고친다.** 뒤의 有/無 를 못 보고 바꾸면 뜻이 뒤집힌다 —
     실제로 「ひるみ無」가 「움찔」이 되어 반대로 읽혔다(2026-09-23, 4칸).
     꼴이 분명한 것만 고치고, 나머지는 check_glossary 에 걸려 사람이 보게 둔다. */
  [/히루미\s*유(?![가-힣])/g, '움찔 있음'],
  /* MT 가 「ひるみ無」를 「음찔무」로 냈다 — 오타(음찔)에 「無」까지 음차했다.
     PRE 에 ひるみ無 를 넣어 앞으로는 안 생기지만, 이미 캐시에 박힌 칸은 여기서 고친다. */
  [/음찔\s*무(?![가-힣])/g, '움찔 없음'], [/음찔/g, '움찔'],
];
/* 문자열이 아니면 **그대로 돌려준다.** String(s) 로 감싸면 MT 실패(null)가
   문자열 "null" 이 되고, 일본어가 없으니 번역 성공으로 통과해 버린다 —
   실제로 그렇게 사전 19칸에 「null」이 박혔다(2026-09-23). 실패는 실패로 남겨야 한다. */
const post = s => (typeof s === 'string' ? POST.reduce((a, [re, ko]) => a.replace(re, ko), s) : s);

// 검사용: 원문에 왼쪽이 있으면 번역에 오른쪽이 있어야 한다.
// 금지어 찾기로는 못 잡는 「사라진 번역」을 잡는 자리다.
const CHECK = [
  [/よろけ/, /경직/], [/オーバーヒート/, /오버 ?히트|OH/], [/兵装/, /무장/],
  [/スラスター/, /슬러스터/], [/シールド/, /실드/], [/制御機構/, /제어\s?기구/],
  [/ダメージ/, /대미지/], [/ファンネル/, /판넬/],
  /* 2026-09-23 에 더함 — 없어서 「히루미」가 18칸이나 살아 있었다.
     이 목록에 없는 말은 아무리 틀려도 안 걸린다. 핵심어는 빠짐없이 적을 것. */
  [/ひるみ/, /움찔/], [/のけぞり/, /젖혀짐/],
];
// 대응어가 빠진 규칙들을 돌려준다(빈 배열이면 통과).
const missing = (jp, ko) => CHECK.filter(([j, k]) => j.test(jp) && !k.test(ko)).map(([j]) => String(j));

module.exports = { protect, post, missing, PRE, POST };
